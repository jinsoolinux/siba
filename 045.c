/*
================================================================================
 [문제 045] 열거형(enum)
================================================================================

 열거형을 사용하여 요일 Sun, Mon, Tue, Wed, Thr, Fri, Sat를 정의하고
 (Sun = 0부터 시작), 각 요일의 값을 출력하세요.

 [실행 결과]
  0 1 2 3 4 5 6

 [힌트]
  - 열거형은 값을 지정하지 않으면 앞의 값보다 1씩 증가합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

// ★ enum : 정수 상수들에 의미 있는 이름을 붙임
//   Sun=0 이후로는 자동으로 1씩 증가 (Mon=1, Tue=2, ...)
enum { Sun = 0, Mon, Tue, Wed, Thr, Fri, Sat };

int main( void )
{
	printf( "%d ", Sun );	// 0
	printf( "%d ", Mon );	// 1
	printf( "%d ", Tue );	// 2
	printf( "%d ", Wed );	// 3
	printf( "%d ", Thr );	// 4
	printf( "%d ", Fri );	// 5
	printf( "%d ", Sat );	// 6

	return 0;
}
