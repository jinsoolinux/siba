/*
================================================================================
 [문제 040] 변수의 메모리 주소 출력하기
================================================================================

 정수형 변수 i = 0, j = 1을 선언하고, 각 변수의 값과 메모리 주소를 출력하세요.

 [실행 결과]  (주소 값은 실행할 때마다, 컴퓨터마다 다릅니다)
  값=0, 메모리주소=000000E1A2D3F8B4
  값=1, 메모리주소=000000E1A2D3F8B0

 [힌트]
  - & 연산자는 변수의 주소를 구합니다.
  - 주소는 %p 서식으로 출력합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i = 0;
	int j = 1;

	// ★ &변수 : 그 변수가 저장된 메모리 주소
	// ★ %p : 포인터(주소)를 16진수로 출력. 인자는 (void *)로 바꿔 주는 것이 표준입니다.
	printf( "값=%d, 메모리주소=%p \n", i, (void *)&i );
	printf( "값=%d, 메모리주소=%p \n", j, (void *)&j );

	return 0;
}
