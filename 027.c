/*
================================================================================
 [문제 027] 조건 연산자 (? :)
================================================================================

 x = 1, y = 2 일 때 조건 연산자를 사용하여 두 수 중 큰 값을 변수 max에 저장하고,
 max의 값을 출력하세요.

 [조건]
  1. if 문을 사용하지 않고 "조건 ? 값1 : 값2" 형태로 작성합니다.

 [실행 결과]
  max = 2

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = 1;
	int y = 2;
	int max;

	// ★ 조건 ? 참일 때의 값 : 거짓일 때의 값
	//   x > y 가 거짓이므로 y의 값(2)이 max에 저장됩니다.
	max = x > y ? x : y;

	printf( "max = %d \n", max );

	return 0;
}

/*
 [참고]
  - 위 코드는 다음 if 문과 같은 의미입니다.
      if( x > y ) max = x;
      else        max = y;
*/
