/*
================================================================================
 [문제 043] 구조체로 성적 합계 구하기
================================================================================

 국어(kor), 영어(eng), 수학(math) 점수를 멤버로 갖는 구조체 tagSungJuk을 정의하고,
 구조체 변수 SJ에 100, 95, 99점을 저장한 뒤 세 과목의 총합을 출력하세요.

 [실행 결과]
  총합 = 294

 [힌트]
  - 구조체 멤버에는 "변수명.멤버명" 으로 접근합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

// ★ 구조체 정의: 서로 관련 있는 여러 변수를 하나로 묶은 새 자료형
struct tagSungJuk
{
	int kor;
	int eng;
	int math;
};	// ★ 구조체 정의 끝의 세미콜론을 잊지 마세요!

int main( void )
{
	struct tagSungJuk SJ;	// 구조체 변수 선언

	SJ.kor  = 100;			// ★ 멤버 접근 연산자( . )
	SJ.eng  = 95;
	SJ.math = 99;

	printf( "총합 = %d ", SJ.kor + SJ.eng + SJ.math );

	return 0;
}
