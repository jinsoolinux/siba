/*
================================================================================
 [문제 047] 문자열을 한 글자씩 출력하는 함수
================================================================================

 문자열을 전달받아 한 글자씩 printf("%c")로 출력하고, 출력한 글자 수를
 반환하는 함수 print()를 만드세요. main()에서 "This is a function !"을 출력합니다.

 [실행 결과]
  This is a function !

 [힌트]
  - 포인터를 증가시키며 '\0'을 만날 때까지 반복합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int print( const char* string );

int main( void )
{
	print( "This is a function !" );	// ★ 반환값을 사용하지 않아도 됩니다.

	return 0;
}

int print( const char* string )
{
	int len = 0;

	while( *string != '\0' )		// ★ 문자열 끝(널 문자)까지 반복
	{
		printf( "%c", *string );	// 현재 가리키는 문자 1개 출력
		string++;					// 번지 값을 1 증가 → 다음 문자
		len++;						// 문자열의 길이를 1 증가
	}

	return len;		// 총 문자열의 길이를 반환
}
