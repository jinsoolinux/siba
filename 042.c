/*
================================================================================
 [문제 042] 포인터로 문자열 길이 구하기
================================================================================

 문자열의 시작 주소를 받아 길이를 반환하는 함수 length()를 직접 만들고,
 "abcde"의 길이를 출력하세요. (strlen() 함수는 사용하지 않습니다.)

 [실행 결과]
  길이 = 5

 [힌트]
  - C의 문자열은 항상 널 문자('\0')로 끝납니다.
  - 포인터를 1씩 증가시키면서 '\0'을 만날 때까지 개수를 세면 됩니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int length( const char* pstr );

int main( void )
{
	int len = length( "abcde" );

	printf( "길이 = %d ", len );	// 길이 = 5

	return 0;
}

int length( const char* pstr )
{
	int len = 0;

	// ★ 문자열의 끝은 널 문자 '\0' (값 0)으로 판단합니다.
	//   원본은 NULL과 비교했지만, NULL은 "포인터"용 상수이므로 문자와 비교할 때는 '\0'을 씁니다.
	while( *pstr != '\0' )
	{
		pstr++;	// ★ 포인터를 다음 문자로 이동 (char는 1바이트이므로 주소가 1 증가)
		len++;	// 문자열의 길이를 1 증가
	}

	return len;
}
