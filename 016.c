/*
================================================================================
 [문제 016] 문자형 상수는 바꿀 수 없다 (오류 고치기)
================================================================================

 아래 코드는 컴파일 오류가 발생합니다. 오류의 원인을 찾아,
 상수의 값은 그대로 두고 출력만 되도록 고치세요.

   #include <stdio.h>
   #define HUNDRED 100
   const char j = 10;
   main()
   {
       HUNDRED = 200;
       j = 200;
       printf( "문자형 상수 HUNDRED의 값은 %d \n", HUNDRED );
       printf( "문자형 상수 j의 값은 %d \n", j );
       getch();
   }

 [고친 후 실행 결과]
  문자형 상수 HUNDRED의 값은 100
  문자형 상수 j의 값은 10

 [힌트]
  - #define 으로 만든 이름과 const 변수는 값을 바꿀 수 없습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

#define HUNDRED 100		// 전처리 후 HUNDRED는 숫자 100으로 바뀝니다.
const char j = 10;		// ★ const : 선언할 때 정한 값을 바꿀 수 없는 변수

int main( void )
{
	// HUNDRED = 200;	// ★ 오류: 100 = 200; 이 되므로 숫자에 대입할 수 없습니다.
	// j = 200;			// ★ 오류: const 변수에는 값을 다시 대입할 수 없습니다.

	printf( "문자형 상수 HUNDRED의 값은 %d \n", HUNDRED );
	printf( "문자형 상수 j의 값은 %d \n", j );

	// getch();	// ★ getch()는 conio.h에 있는 비표준 함수라 다른 컴파일러에서는 오류가 납니다.

	return 0;
}
