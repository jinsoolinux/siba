/*
================================================================================
 [문제 049] getch()로 키 입력 받기 (Windows 전용)
================================================================================

 "아무키나 누르세요..."를 출력한 뒤, 키보드에서 키 하나를 입력받아
 "(문자) 키가 눌려졌습니다."를 출력하세요. Enter 키 없이 바로 반응해야 합니다.

 [실행 결과]  (a 키를 눌렀을 때)
  아무키나 누르세요...
  a 키가 눌려졌습니다.

 [힌트]
  - conio.h의 getch() 함수는 Enter 없이 키 하나를 바로 읽고, 화면에 표시하지 않습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>
#include <conio.h>		// ★ getch() 선언 (Windows 전용 헤더)

int main( void )
{
	int ch;

	printf( "아무키나 누르세요...\n" );

	ch = _getch();		// ★ 키 하나를 즉시 읽음 (입력한 문자가 화면에 보이지 않음)
						//   최신 Visual Studio에서는 getch() 대신 _getch()를 사용합니다.

	printf( "%c 키가 눌려졌습니다. ", ch );

	return 0;
}

/*
 [참고]
  - conio.h와 getch()는 표준 C가 아니므로 Windows(Visual Studio, MinGW)에서만 동작합니다.
  - 표준 함수 getchar()는 Enter를 눌러야 입력이 전달됩니다.
*/
