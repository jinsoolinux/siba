/*
================================================================================
 [문제 024] 증감 연산자 (전위/후위)
================================================================================

 x = 1 에서 시작하여 다음 순서로 printf()를 실행했을 때 출력되는 값을 예측해 보고,
 프로그램으로 확인하세요.
   x++,  x++,  ++x,  x--,  x--,  --x

 [실행 결과]
  x = 1
  x = 2
  x = 4
  x = 4
  x = 3
  x = 1

 [힌트]
  - x++ : 현재 값을 먼저 사용한 뒤 1 증가 (후위)
  - ++x : 먼저 1 증가시킨 뒤 그 값을 사용 (전위)

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = 1;

	printf( "x = %d \n", x++ );		// ★ 1 출력 후 x는 2
	printf( "x = %d \n", x++ );		//    2 출력 후 x는 3
	printf( "x = %d \n", ++x );		// ★ x를 4로 만든 후 4 출력
	printf( "x = %d \n", x-- );		//    4 출력 후 x는 3
	printf( "x = %d \n", x-- );		//    3 출력 후 x는 2
	printf( "x = %d \n", --x );		//    x를 1로 만든 후 1 출력

	return 0;
}

/*
 [참고]
  - 한 문장 안에서 같은 변수에 증감 연산자를 여러 번 쓰면(예: x++ + x++)
    결과가 정의되지 않으므로 절대 그렇게 쓰지 마세요.
*/
