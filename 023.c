/*
================================================================================
 [문제 023] 산술 연산자 (+, -, *, /)
================================================================================

 x = 4, y = 2 일 때 다음 식의 결과를 각각 계산하여 출력하세요.
   x + y,  x - y,  x * y,  x / y,  (x+y) * (x-y),  (x*y) + (x/y),
   x + y + 2004,  2004 - x - y

 [실행 결과]
  x + y         = 6
  x - y         = 2
  x * y         = 8
  x / y         = 2
  (x+y) * (x-y) = 12
  (x*y) + (x/y) = 10
  x + y + 2004  = 2010
  2004 - x - y  = 1998

 [힌트]
  - 괄호 안의 식이 먼저 계산되고, *와 /는 +와 -보다 먼저 계산됩니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = 4;
	int y = 2;
	int z;

	z = x + y;			printf( "x + y         = %d \n", z );	// 6
	z = x - y;			printf( "x - y         = %d \n", z );	// 2
	z = x * y;			printf( "x * y         = %d \n", z );	// 8
	z = x / y;			printf( "x / y         = %d \n", z );	// 2
	z = (x+y) * (x-y);	printf( "(x+y) * (x-y) = %d \n", z );	// ★ 괄호 먼저: 6 * 2 = 12
	z = (x*y) + (x/y);	printf( "(x*y) + (x/y) = %d \n", z );	// 8 + 2 = 16
	z = x + y + 2004;	printf( "x + y + 2004  = %d \n", z );	// ★ 같은 우선순위는 왼쪽부터 계산
	z = 2004 - x - y;	printf( "2004 - x - y  = %d \n", z );	// (2004 - 4) - 2 = 1998

	return 0;
}

