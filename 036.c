/*
================================================================================
 [문제 036] do~while 문
================================================================================

 do~while 문을 사용하여 1부터 10까지의 합을 구해 출력하세요.

 [실행 결과]
  hap = 55

 [힌트]
  - do~while 문은 본문을 먼저 실행한 뒤 조건을 검사합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i = 1;
	int hap = 0;

	// ★ do~while 은 조건과 상관없이 본문이 최소 1번은 실행됩니다.
	do
	{
		hap = hap + i;
		i++;
	} while( i <= 10 );		// ★ while 뒤에 세미콜론(;)을 꼭 붙여야 합니다.

	printf( "hap = %d ", hap );

	return 0;
}
