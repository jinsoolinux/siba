/*
================================================================================
 [문제 012] 정수형(int) 변수의 범위
================================================================================

 int 형 변수 i에 2000000000(20억)을, unsigned int 형 변수 j에 4000000000(40억)을,
 int 형 변수 k에 문자 'b'를 대입한 뒤 각각 출력하세요.

 [조건]
  1. i와 k는 %d, j는 %u 서식으로 출력합니다.

 [실행 결과]
  정수형 변수 i의 값은 2000000000
  정수형 변수 j의 값은 4000000000
  정수형 변수 k의 값은 98

 [힌트]
  - int는 약 -21억 ~ 21억, unsigned int는 0 ~ 약 42억까지 저장할 수 있습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i;
	unsigned int j;
	int k;

	i = 2000000000;		// ★ int의 최댓값(2147483647) 이내이므로 정상 저장
	j = 4000000000u;	// ★ int로는 담을 수 없지만 unsigned int(최대 4294967295)는 가능
						//   숫자 뒤의 u는 "부호 없는 정수 상수"라는 뜻입니다.
	k = 'b';			// 문자 'b'의 아스키 코드 98이 저장됩니다.

	printf( "정수형 변수 i의 값은 %d \n", i );
	printf( "정수형 변수 j의 값은 %u \n", j );	// ★ unsigned는 %u로 출력해야 올바르게 보입니다.
	printf( "정수형 변수 k의 값은 %d \n", k );

	return 0;
}

