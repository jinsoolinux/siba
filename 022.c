/*
================================================================================
 [문제 022] 부호 연산자 (+, -)
================================================================================

 x = +4, y = -2 일 때 x + (-y) 와 -x + (+y) 의 결과를 출력하세요.

 [실행 결과]
   x + (-y) = 6
  -x + (+y) = -6

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = +4;
	int y = -2;

	// ★ 단항 연산자 - 는 부호를 반대로 바꿉니다. -y = -(-2) = 2
	printf( " x + (-y) = %d \n",  x + (-y) );	//  4 + 2 = 6
	printf( "-x + (+y) = %d \n", -x + (+y) );	// -4 + (-2) = -6

	return 0;
}
