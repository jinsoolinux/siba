/*
================================================================================
 [문제 035] while 문으로 1부터 10까지 더하기
================================================================================

 while 문을 사용하여 1부터 10까지의 합을 구해 출력하세요.

 [실행 결과]
  hap = 55

 [힌트]
  - while( 조건 ) 은 조건이 참인 동안 본문을 반복합니다.
  - 반복할 때마다 i를 1씩 증가시키지 않으면 무한 루프에 빠집니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i = 1;		// ★ while 문은 반복 변수를 미리 초기화해 둬야 합니다.
	int hap = 0;

	while( i <= 10 )	// i가 10보다 작거나 같은 동안 반복
	{
		hap = hap + i;
		i++;			// ★ 이 줄이 없으면 i가 계속 1이라 무한 루프!
	}

	printf( "hap = %d ", hap );		// hap = 55

	return 0;
}
