/* ============================== 정답 코드 ============================== */

#include <stdio.h>

// ★ #define 이름 값  →  컴파일 전에 코드 속 "이름"이 "값"으로 치환됩니다.
//   끝에 세미콜론(;)을 붙이지 않는다는 점에 주의하세요.
#define  X   1
#define  PI  3.141592

int main( void )
{
	double z;		// ★ 소수점이 있는 값은 실수형(double)에 저장합니다.

	z = X + PI;		// 전처리 후에는 z = 1 + 3.141592; 가 됩니다.

	printf( "%f", z );	// ★ double은 %f로 출력합니다.

	return 0;
}
