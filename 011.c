/*
================================================================================
 [문제 011] 문자형(char) 변수의 범위
================================================================================

 char 형 변수 ch와 unsigned char 형 변수 j에 똑같이 200을 대입하고,
 char 형 변수 k에는 문자 'a'를 대입한 뒤 세 변수의 값을 정수로 출력하세요.
 ch와 j의 출력값이 왜 다른지 생각해 보세요.

 [실행 결과]  (Visual Studio, gcc 기준)
  문자형 변수 ch의 값은 -56
  문자형 변수 j의 값은 200
  문자형 변수 k의 값은 97

 [힌트]
  - char는 -128 ~ 127, unsigned char는 0 ~ 255 범위의 값을 저장합니다.
  - 문자 'a'는 내부적으로 아스키 코드 값(정수)으로 저장됩니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	char ch;
	unsigned char j;
	char k;

	ch = 200;	// ★ char(-128~127)의 범위를 넘으므로 200-256 = -56이 저장됩니다.
	j = 200;	// ★ unsigned char(0~255)는 200을 그대로 저장할 수 있습니다.
	k = 'a';	// ★ 문자 'a'는 아스키 코드 97로 저장됩니다.

	printf( "문자형 변수 ch의 값은 %d \n", ch );
	printf( "문자형 변수 j의 값은 %u \n", j );	// %u : 부호 없는 정수 출력
	printf( "문자형 변수 k의 값은 %d \n", k );

	return 0;
}

