/*
================================================================================
 [문제 037] goto 문으로 중첩 반복 빠져나오기
================================================================================

 바깥 반복은 1~100, 안쪽 반복은 1~9로 구구단을 출력하되,
 9 * 9 를 출력한 직후 goto 문을 사용하여 두 반복문을 한꺼번에 빠져나오세요.

 [실행 결과]  (앞부분과 뒷부분만 표시)
  1 * 1 =  1
  ...
  9 * 9 = 81

 [힌트]
  - break는 가장 가까운 반복문 하나만 빠져나옵니다.
  - goto 레이블; 을 쓰면 "레이블:" 이 붙은 위치로 바로 이동합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i;
	int j;

	for( i = 1; i <= 100; i++ )
	{
		for( j = 1; j <= 9; j++ )
		{
			printf( "%d * %d = %2d \n", i, j, i * j );

			// ★ 9 * 9 이후에는 두 반복문을 한 번에 탈출
			if( i == 9 && j == 9 ) goto ku_ku_end;
		}
	}

ku_ku_end:		// ★ 레이블: 이름 뒤에 콜론(:)을 붙입니다.
	return 0;
}

/*
 [참고]
  - goto는 코드의 흐름을 알아보기 어렵게 만들기 때문에 꼭 필요한 경우
    (중첩 반복 탈출 등)에만 제한적으로 사용하는 것이 좋습니다.
*/
