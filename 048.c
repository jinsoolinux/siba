/*
================================================================================
 [문제 048] 지역 변수와 전역 변수
================================================================================

 전역 변수 x = 20, main() 안의 지역 변수 x = 5를 선언하세요.
 그리고 다음 세 곳에서 x를 출력하여 어떤 x가 사용되는지 확인하세요.
   1. main() 안
   2. 매개변수 x로 10을 받는 함수 print_x() 안
   3. 매개변수가 없는 함수 print_gx() 안

 [실행 결과]
  x = 5
  x = 10
  x = 20

 [힌트]
  - 이름이 같으면 가장 가까운(안쪽) 범위의 변수가 우선합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

void print_x( int x );
void print_gx( void );

int x = 20;		// ★ 전역 변수: 함수 밖에 선언, 프로그램 어디서나 사용 가능

int main( void )
{
	int x = 5;	// ★ 지역 변수: 이 블록 안에서는 전역 x를 가립니다.

	printf( "x = %d \n", x );	// 5 (지역 변수)
	print_x( 10 );				// 10 (매개변수)
	print_gx();					// 20 (전역 변수)

	return 0;
}

void print_x( int x )	// ★ 매개변수도 그 함수의 지역 변수입니다.
{
	printf( "x = %d \n", x );
}

void print_gx( void )
{
	printf( "x = %d \n", x );	// ★ 이 함수에는 지역 x가 없으므로 전역 x 사용
}
