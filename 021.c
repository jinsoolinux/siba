/*
================================================================================
 [문제 021] printf()의 반환값
================================================================================

 x = 1, y = 2 일 때 z = x + y를 계산해 "z의 값 : 3"을 출력하세요.
 이때 printf()가 돌려주는 값을 변수 zz에 저장하고, zz의 값도 출력해 보세요.

 [실행 결과]
  z의 값 : 3
  zz의 값 : 14

 [힌트]
  - printf()는 화면에 출력한 문자의 개수(바이트 수)를 반환합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = 1;		// ★ 선언과 동시에 값을 넣는 것을 "초기화"라고 합니다.
	int y = 2;
	int z;
	int zz;

	z = x + y;

	// ★ printf()는 출력한 바이트 수를 반환합니다.
	zz = printf( "z의 값 : %d \n", z );

	printf( "zz의 값 : %d \n", zz );

	return 0;
}

/*
 [참고]
  - 한글은 인코딩에 따라 한 글자가 2바이트(CP949) 또는 3바이트(UTF-8)이므로
    zz의 값은 환경에 따라 다르게 나올 수 있습니다.
    (윈도우 CP949 환경에서는 "z의 값 : 3 \n" = 12바이트)
*/
