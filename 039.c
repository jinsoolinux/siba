/*
================================================================================
 [문제 039] 배열에 저장된 점수 출력하기
================================================================================

 10명의 국어 점수 {100, 90, 35, 60, 75, 55, 95, 80, 90, 70}을 배열 kor에 저장하고,
 for 문으로 모든 점수를 한 줄에 출력하세요.

 [실행 결과]
  100 90 35 60 75 55 95 80 90 70

 [힌트]
  - 배열의 첫 번째 요소는 kor[0], 마지막 요소는 kor[9]입니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	// ★ 배열 선언과 동시에 중괄호로 초기화
	int kor[10] = {100, 90, 35, 60, 75, 55, 95, 80, 90, 70};
	int i;

	// ★ 배열 인덱스는 0부터 시작하므로 0 ~ 9 까지 반복합니다.
	//   i <= 10 으로 쓰면 범위를 벗어나 엉뚱한 메모리를 읽게 됩니다.
	for( i = 0; i < 10; i++ )
	{
		printf( "%d ", kor[i] );
	}

	return 0;
}
