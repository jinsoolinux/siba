/*
================================================================================
 [문제 006] for 문으로 1부터 10까지 더하기
================================================================================

 for 문을 사용하여 1부터 10까지의 합을 구해 출력하세요.

 [실행 결과]
  1부터 10까지의 합: 55

 [힌트]
  - 합을 저장할 변수는 0으로 초기화해야 합니다.
  - for( 초기식; 조건식; 증감식 ) 의 순서로 작성합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/
#include <stdio.h>

int main(void)
{
    int i =0;
    int hap = 0;
    for(i=1;i<=10;i++)
    {
        hap =hap+i;
    }
    printf("1~5:%d\n",hap);
    return 0;
}










