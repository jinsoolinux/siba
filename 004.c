/*
================================================================================
 [문제 004] if~else 문으로 크기 비교하기 (1)
================================================================================

 정수형 변수 x에 10을 대입하고, y에는 x - 5의 결과를 대입하세요.
 x가 y보다 크면 "x의 값이 y보다 큽니다."를,
 그렇지 않으면 "x의 값이 y보다 작거나 같습니다."를 출력하세요.

 [실행 결과]
  x의 값이 y보다 큽니다.

 [힌트]
  - if( 조건 ) { ... } else { ... } 구조를 사용합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/
#include <stdio.h>

int main(void)
{
    int x;
    int y; 
    x=10;
    y=x-5;

    if(x>y)
    {
        printf("x>y");
    }
    else
    {
        printf("x<=y");
    }

    return 0;
}








