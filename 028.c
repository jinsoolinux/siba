/*
================================================================================
 [문제 028] 변수를 한 줄에 여러 개 선언하기
================================================================================

 x = 1, y = 2, max 세 변수를 한 줄에 선언하고, 조건 연산자로 큰 값을 max에 저장한 뒤
 max, x, y를 한 번의 printf()로 출력하세요.

 [실행 결과]
  max = 2, x = 1, y = 2

 [힌트]
  - 같은 자료형의 변수는 쉼표(,)로 구분하여 한 줄에 선언할 수 있습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = 1, y = 2, max;	// ★ 쉼표로 여러 변수 선언 (max는 초기화하지 않음)

	max = x > y ? x : y;

	// ★ 서식 문자(%d)의 개수와 뒤에 오는 인자의 개수·순서가 일치해야 합니다.
	printf( "max = %d, x = %d, y = %d", max, x, y );

	return 0;
}
