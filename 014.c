/*
================================================================================
 [문제 014] 참과 거짓 (논리값)
================================================================================

 정수형 변수 b에 10 > 5 의 결과를, j에 10 > 20 의 결과를 저장한 뒤 값을 출력하세요.
 그리고 b, j, -1 을 각각 if 문의 조건으로 사용하여 참/거짓 여부를 출력하세요.

 [실행 결과]
  논리형 변수 b의 값은 1
  논리형 변수 j의 값은 0
  10 > 5의 식은 참입니다.
  10 > 20의 식은 거짓입니다.
  -1은 참입니다.

 [힌트]
  - C 언어에서 비교 연산의 결과는 참이면 1, 거짓이면 0입니다.
  - if 문은 0이면 거짓, 0이 아닌 모든 값은 참으로 판단합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int b;
	int j;

	b = 10 > 5;		// ★ 참 → 1
	j = 10 > 20;	// ★ 거짓 → 0

	printf( "논리형 변수 b의 값은 %d \n", b );
	printf( "논리형 변수 j의 값은 %d \n", j );

	if( b )		// b = 1 → 참
	{
		printf( "10 > 5의 식은 참입니다. \n" );
	}
	else
	{
		printf( "10 > 5의 식은 거짓입니다. \n" );
	}

	if( j )		// j = 0 → 거짓
	{
		printf( "10 > 20의 식은 참입니다. \n" );
	}
	else
	{
		printf( "10 > 20의 식은 거짓입니다. \n" );
	}

	if( -1 )	// ★ 0이 아닌 값은 음수라도 모두 참입니다!
	{
		printf( "-1은 참입니다. \n" );
	}
	else
	{
		printf( "-1은 거짓입니다. \n" );
	}

	return 0;
}
