/*
================================================================================
 [문제 044] 공용체(union)의 메모리 공유
================================================================================

 int 형 멤버 i와 float 형 멤버 d를 갖는 공용체 tagVariant를 정의하세요.
 V.i에 0을 넣은 다음 V.d에 5.5를 넣고, V.i와 V.d를 출력하여
 공용체의 특징을 확인하세요.

 [실행 결과]
  V.i = 1085276160
  V.d = 5.500000

 [힌트]
  - 공용체의 모든 멤버는 같은 메모리 공간을 함께 사용합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

// ★ union : 모든 멤버가 같은 메모리를 공유 (크기 = 가장 큰 멤버의 크기)
union tagVariant
{
	int i;
	float d;
};

int main( void )
{
	union tagVariant V;

	V.i = 0;
	V.d = 5.5f;		// ★ 같은 메모리에 5.5의 float 비트 패턴을 덮어씀

	// ★ V.i는 5.5를 표현하는 비트(0x40B00000)를 정수로 해석한 값이 나옵니다.
	printf( "V.i = %d \n", V.i );	// V.i = 1085276160
	printf( "V.d = %f \n", V.d );	// V.d = 5.500000

	return 0;
}

/*
 [참고]
  - 구조체는 멤버마다 별도의 공간을 갖지만, 공용체는 한 번에 한 멤버만
    의미 있는 값을 가질 수 있습니다. 메모리를 아낄 때 사용합니다.
*/
