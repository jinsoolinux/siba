/*
================================================================================
 [문제 030] 형 변환 연산자 (cast)
================================================================================

 x = 5, y = 2 일 때 x / y 의 결과를 정수로 출력하고,
 형 변환을 이용하여 실수 나눗셈 결과(2.5)도 출력하세요.

 [실행 결과]
  2
  2.500000

 [힌트]
  - 정수 / 정수 의 결과는 소수점 이하가 버려진 정수입니다.
  - (double)x 처럼 쓰면 x를 잠시 실수로 바꿔서 계산할 수 있습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = 5, y = 2;

	printf( "%d \n", x / y );			// ★ 정수 나눗셈: 2.5 → 2 (소수점 이하 버림)
	printf( "%f \n", (double)x / y );	// ★ x를 double로 바꾸면 실수 나눗셈이 되어 2.500000

	return 0;
}

/*
 [참고]
  - (double)(x / y) 라고 쓰면 정수 나눗셈(2)이 먼저 끝난 뒤 변환되므로 2.000000이 됩니다.
    괄호 위치에 주의하세요.
*/
