/*
================================================================================
 [문제 033] 중첩 for 문으로 구구단 출력하기
================================================================================

 이중 for 문을 사용하여 1단부터 9단까지 구구단을 출력하세요.

 [조건]
  1. "i * j = 결과" 형태로 출력하고, 결과는 2자리 폭(%2d)으로 맞춥니다.

 [실행 결과]  (앞부분과 뒷부분만 표시)
  1 * 1 =  1
  1 * 2 =  2
  ...
  9 * 8 = 72
  9 * 9 = 81

 [힌트]
  - 바깥 for는 단(i), 안쪽 for는 곱하는 수(j)를 담당합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i;
	int j;

	for( i = 1; i <= 9; i++ )			// 바깥 반복: 단(1~9)
	{
		for( j = 1; j <= 9; j++ )		// ★ 안쪽 반복: 바깥 반복 1번당 9번씩 실행
		{
			printf( "%d * %d = %2d \n", i, j, i * j );	// ★ %2d : 2칸 폭으로 오른쪽 정렬
		}
	}

	return 0;
}
