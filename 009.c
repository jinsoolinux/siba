/*
================================================================================
 [문제 009] 주석 달기 연습
================================================================================

 1부터 10까지의 합을 구해 "1부터 10까지의 합 : 55" 형태로 출력하는
 프로그램을 작성하세요. 이때 코드의 각 부분에 설명 주석을 달아 보세요.

 [조건]
  1. 한 줄 주석(//)과 여러 줄 주석(슬래시-별 로 시작해 별-슬래시 로 끝나는 주석)을
     모두 사용합니다.
  2. for 문이 실행되는 순서를 여러 줄 주석으로 설명합니다.

 [실행 결과]
  1부터 10까지의 합 : 55

 [힌트]
  - 주석은 컴파일러가 무시하므로 프로그램 실행에 영향을 주지 않습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i;			// 정수형 변수 i를 정의합니다.
	int hap = 0;	// 정수형 변수 hap을 정의하고 0으로 초기화합니다.

	/*
	   ★ 여러 줄 주석은 슬래시+별로 시작해서 별+슬래시로 끝납니다.
	      (여러 줄 주석 안에 또 다른 여러 줄 주석을 중첩할 수는 없습니다.
	       안쪽의 별+슬래시에서 주석이 끝나 버리기 때문입니다.)

	   for문은 다음처럼 실행됩니다.
	   1. i는 1을 초기값으로 설정합니다.
	   2. i가 10보다 작거나 같은지 검사합니다.
	   3. 현재의 hap의 값과 i값을 더하여 hap에 대입합니다.
	   4. i는 1씩 증가합니다.
	*/
	for( i = 1; i <= 10; i = i + 1 )
	{
		hap = hap + i;	// hap과 i를 더하여 hap에 대입합니다.
	}

	/* "1부터 10까지의 합 : 55"가 화면에 표시됩니다. */
	printf( "1부터 10까지의 합 : %d", hap );

	return 0;
}
