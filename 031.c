/*
================================================================================
 [문제 031] sizeof 연산자
================================================================================

 char, int, double 형 변수를 하나씩 선언하고, sizeof 연산자를 사용하여
 각 변수가 차지하는 메모리 크기(바이트)를 출력하세요.

 [실행 결과]
  1
  4
  8

 [힌트]
  - sizeof(변수) 또는 sizeof(자료형) 으로 크기를 구할 수 있습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	char i;
	int  j;
	double k;

	// ★ sizeof의 결과는 size_t 형이므로 %zu로 출력하는 것이 정확합니다.
	//   (오래된 컴파일러라면 (int)sizeof(i) 로 바꾸고 %d를 사용하세요.)
	printf( "%zu \n", sizeof(i) );		// 1
	printf( "%zu \n", sizeof(j) );		// 4
	printf( "%zu \n", sizeof(k) );		// 8

	return 0;
}

/*
 [참고]
  - char는 항상 1바이트이지만, int 등의 크기는 시스템에 따라 다를 수 있습니다.
*/
