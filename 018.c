/*
================================================================================
 [문제 018] 실수형 상수
================================================================================

 #define으로 PI를 3.141592로 정의하고, const double 형 상수 j를 1.23456789로
 선언한 뒤, 두 상수의 값을 %f 서식으로 출력하세요.

 [실행 결과]
  실수형 상수 PI의 값은 3.141592
  실수형 상수 j의 값은 1.234568
  실수형 상수 j의 값(8자리)은 1.23456789

 [힌트]
  - %f는 소수점 아래 6자리까지만 출력하므로, j는 반올림되어 보입니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

#define PI 3.141592
const double j = 1.23456789;

int main( void )
{
	//PI = 3.141592;		// 에러 발생 : 상수에는 대입 불가
	//j = 1.23456789;		// 에러 발생 : const 변수는 수정 불가

	printf( "실수형 상수 PI의 값은 %f \n", PI );
	printf( "실수형 상수 j의 값은 %f \n", j );	// ★ 1.23456789 → 1.234568 (7번째 자리에서 반올림)

	// ★ 더 많은 자리를 보고 싶다면 %.8f 처럼 정밀도를 지정합니다.
	printf( "실수형 상수 j의 값(8자리)은 %.8f \n", j );

	return 0;
}
