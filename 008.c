/*
================================================================================
 [문제 008] 1부터 N까지의 합을 구하는 함수 만들기
================================================================================

 정수 하나(value)를 전달받아 1부터 value까지의 합을 계산해 돌려주는
 함수 hapf()를 작성하세요. 그리고 main() 함수에서 hapf()를 세 번 호출하여
 1~10, 1~100, 1~1000까지의 합을 각각 출력하세요.

 [조건]
  1. 함수 원형은 int hapf( int value ); 로 합니다.
  2. hapf() 함수의 정의는 main() 함수 아래쪽에 작성합니다.
     (main()보다 아래에 정의하므로 위쪽에 함수 원형을 선언해야 합니다.)
  3. 합은 for 문으로 계산합니다.

 [실행 결과]
  1부터   10까지의 합은 55
  1부터  100까지의 합은 5050
  1부터 1000까지의 합은 500500

 [힌트]
  - 합을 저장할 변수는 반드시 0으로 초기화하고 시작하세요.
  - printf() 안에서 함수를 호출하면, 함수의 반환값이 바로 출력됩니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

// ★ 함수 원형(prototype) 선언
//   hapf()의 정의가 main()보다 아래에 있으므로, 컴파일러에게
//   "이런 이름·매개변수·반환형의 함수가 있다"고 미리 알려 줘야 합니다.
int hapf( int value );

int main( void )
{
	// ★ printf()의 인자로 함수 호출을 바로 넣을 수 있습니다.
	//   hapf(10)이 먼저 실행되고, 그 반환값(55)이 %d 자리에 출력됩니다.
	printf( "1부터   10까지의 합은 %d \n", hapf( 10 ) );
	printf( "1부터  100까지의 합은 %d \n", hapf( 100 ) );
	printf( "1부터 1000까지의 합은 %d \n", hapf( 1000 ) );

	return 0;
}

// 1부터 value까지의 합을 구해 반환하는 함수
int hapf( int value )
{
	int i;
	int hap = 0;	// ★ 누적 변수는 반드시 0으로 초기화!

	for( i = 1; i <= value; i = i + 1 )
	{
		hap = hap + i;	// hap += i; 로 줄여 쓸 수도 있습니다.
	}

	return hap;		// ★ 계산한 합을 호출한 곳으로 돌려줍니다.
}

/*
 [참고]
  - 지역 변수 i, hap은 hapf()가 호출될 때마다 새로 만들어지므로
    세 번 호출해도 서로 값이 섞이지 않습니다.
*/
