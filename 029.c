/*
================================================================================
 [문제 029] 비트 연산자 (&, ~, ^, >>, <<)
================================================================================

 unsigned char 형 변수 ch = 255, mask = 0x7F 일 때 다음 결과를 출력하세요.
   ch,  ch & mask,  (char)~ch,  ch ^ ch,  ch >> 1,  mask << 1

 [실행 결과]
  255
  127
  0
  0
  127
  254

 [힌트]
  - 255 = 1111 1111(2진수), 0x7F = 0111 1111(2진수)
  - & : AND,  ~ : NOT,  ^ : XOR,  >> : 오른쪽 시프트,  << : 왼쪽 시프트

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	unsigned char ch = 255, mask = 0x7F;	// ★ 0x로 시작하면 16진수 (0x7F = 127)

	printf( "%d \n", ch );				// 255
	printf( "%d \n", ch & mask );		// ★ 11111111 & 01111111 = 01111111 = 127
	printf( "%d \n", (char) ~ch );		// ★ ~11111111 = 00000000 = 0
	printf( "%d \n", ch ^ ch );			// ★ 같은 값끼리 XOR 하면 항상 0
	printf( "%d \n", ch >> 1 );			// ★ 오른쪽으로 1비트 이동 = 2로 나누기 → 127
	printf( "%d \n", mask << 1 );		// ★ 왼쪽으로 1비트 이동 = 2 곱하기 → 254

	return 0;
}

/*
 [참고]
  - (char)를 빼고 ~ch 를 출력하면 -256이 나옵니다. 연산 전에 ch가 int로
    승격(integer promotion)되어 상위 비트까지 모두 뒤집히기 때문입니다.
*/
