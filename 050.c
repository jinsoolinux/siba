/*
================================================================================
 [문제 050] 매크로 함수 MAX, MIN
================================================================================

 두 값 중 큰 값을 구하는 매크로 MAX(a,b)와 작은 값을 구하는 매크로 MIN(a,b)를
 #define으로 만들고, i = 5, j = 7에 대해 최대값과 최소값을 출력하세요.

 [실행 결과]
  최대값은 7입니다.
  최소값은 5입니다.

 [힌트]
  - 매크로는 함수처럼 보이지만, 실제로는 코드가 그대로 치환됩니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

// ★ 매크로 함수는 인자와 전체 식을 괄호로 감싸야 안전합니다.
//   (원본처럼 a > b ? a : b 로만 쓰면 MAX(i, j) * 2 같은 식에서 엉뚱하게 계산됩니다.)
#define MAX(a,b) ((a) > (b) ? (a) : (b))
#define MIN(a,b) ((a) < (b) ? (a) : (b))

int main( void )
{
	int i, j;

	i = 5;
	j = 7;

	// 전처리 후: ((i) > (j) ? (i) : (j))
	printf( "최대값은 %d입니다. \n", MAX( i, j ) );
	printf( "최소값은 %d입니다. \n", MIN( i, j ) );

	return 0;
}

