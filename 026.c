/*
================================================================================
 [문제 026] 논리 연산자 (&&,
================================================================================

 x = 5, y = 2 일 때 다음 세 조건을 검사하여 참이면 메시지를 출력하세요.
   1. x가 0보다 크고 10보다 작다.          → "0 < x < 10"
   2. x가 0보다 작거나 y가 2이다.           → "x가 0보다 작거나, y는 2입니다."
   3. x가 y보다 큰 것이 아니다.             → "x가 y보다 크지 않습니다."

 [실행 결과]
  0 < x < 10
  x가 0보다 작거나, y는 2입니다.

 [힌트]
  - && : 둘 다 참일 때 참,  || : 하나라도 참이면 참,  ! : 참/거짓을 뒤집음

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = 5;
	int y = 2;

	// ★ 수학식 0 < x < 10 은 C에서 x > 0 && x < 10 으로 써야 합니다.
	if( x > 0 && x < 10 )
	{
		printf( "0 < x < 10 \n" );
	}

	// ★ || 는 앞의 조건이 참이면 뒤의 조건은 검사하지도 않습니다. (단락 평가)
	if( x < 0 || y == 2 )
	{
		printf( "x가 0보다 작거나, y는 2입니다. \n" );
	}

	// x > y 는 참이므로 !(참) = 거짓 → 출력되지 않습니다.
	if( !(x > y) )
	{
		printf( "x가 y보다 크지 않습니다. \n" );
	}

	return 0;
}
