/*
================================================================================
 [문제 010] 컴파일 오류 찾아 고치기
================================================================================

 아래 코드는 1부터 10까지의 합을 구하려는 프로그램이지만
 컴파일 오류가 2군데 있습니다. 오류를 모두 찾아 고치세요.

   #include <stdio.h>
   main()
   {
       //int i;
       int hap = 0;
       for( i = 1; i <= 10; i = i + 1 )
       {
           hap = hap + i
       }
       printf( "1부터 10까지의 합 : %d", hap );
   }

 [고친 후 실행 결과]
  1부터 10까지의 합 : 55

 [힌트]
  - 컴파일러의 오류 메시지에 표시된 줄 번호 근처를 살펴보세요.
  - 선언되지 않은 변수, 빠진 기호가 없는지 확인하세요.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i;		// ★ 오류 1: 변수 선언이 주석 처리되어 있었습니다.
				//   선언하지 않은 변수를 사용하면 "선언되지 않은 식별자" 오류가 납니다.
	int hap = 0;

	for( i = 1; i <= 10; i = i + 1 )
	{
		hap = hap + i;	// ★ 오류 2: 문장 끝에 세미콜론(;)이 빠져 있었습니다.
	}

	printf( "1부터 10까지의 합 : %d", hap );

	return 0;
}
