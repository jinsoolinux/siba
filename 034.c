/*
================================================================================
 [문제 034] switch~case 문
================================================================================

 정수형 변수 i = 5 일 때 switch 문을 사용하여
 i가 1이면 "i는 1입니다.", 2이면 "i는 2입니다.",
 그 밖의 값이면 "i는 (i값)입니다."를 출력하세요.

 [실행 결과]
  i는 5입니다.

 [힌트]
  - 각 case 끝에는 break를 넣어야 다음 case로 넘어가지 않습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i = 5;

	switch( i )
	{
	case 1:
		printf( "i는 1입니다. " );
		break;		// ★ break가 없으면 아래 case의 문장까지 계속 실행됩니다!
	case 2:
		printf( "i는 2입니다. " );
		break;
	default:		// ★ 어떤 case에도 해당하지 않으면 default가 실행됩니다.
		printf( "i는 %d입니다.", i );
		break;
	}

	return 0;
}
