/*
================================================================================
 [문제 025] 관계 연산자
================================================================================

 x = 1, y = 2, z = 3 일 때 관계 연산자(==, !=, >, <, >=, <=)를 사용하여
 아래 6가지 조건을 검사하고, 참인 경우에만 해당 문장을 출력하세요.
   x == y,  x != y,  x > y,  x < y,  y >= z,  y <= z

 [실행 결과]
  x는 y와 같지 않습니다.
  x는 y보다 작습니다.
  y는 z보다 작거나 같습니다.

 [힌트]
  - 같다는 = 가 아니라 == 입니다. (= 는 대입 연산자)

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int x = 1;
	int y = 2;
	int z = 3;

	// ★ if 문의 본문이 한 줄이면 중괄호를 생략할 수 있습니다.
	if( x == y ) printf( "x는 y와 같습니다. \n" );			// ★ == (같다) 와 = (대입)을 헷갈리지 마세요!
	if( x != y ) printf( "x는 y와 같지 않습니다. \n" );
	if( x >  y ) printf( "x는 y보다 큽니다. \n" );
	if( x <  y ) printf( "x는 y보다 작습니다. \n" );
	if( y >= z ) printf( "y는 z보다 크거나 같습니다. \n" );
	if( y <= z ) printf( "y는 z보다 작거나 같습니다. \n" );

	return 0;
}
