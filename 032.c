/*
================================================================================
 [문제 032] 중첩 if 문과 else if
================================================================================

 i = 1, j = 2, k = 7 일 때, i가 1이고 j가 2인 경우에 한해
 k가 3, 4, 5이면 각각 "i=1, j=2, k=3입니다." 등을 출력하고,
 그 밖의 값이면 "i=1, j=2, k=(k값)입니다."를 출력하세요.

 [실행 결과]
  i=1, j=2, k=7입니다.

 [힌트]
  - if 안에 또 if를 넣을 수 있고, else if로 여러 조건을 차례로 검사할 수 있습니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	int i = 1;
	int j = 2;
	int k = 7;

	if( i == 1 )
	{
		if( j == 2 )	// ★ if 안의 if (중첩 if)
		{
			// ★ else if는 위의 조건이 모두 거짓일 때만 차례로 검사됩니다.
			if( k == 3 )
				printf( "i=1, j=2, k=3입니다." );
			else if( k == 4 )
				printf( "i=1, j=2, k=4입니다." );
			else if( k == 5 )
				printf( "i=1, j=2, k=5입니다." );
			else	// 위의 조건이 모두 거짓이면 실행
				printf( "i=1, j=2, k=%d입니다.", k );
		}
	}

	return 0;
}

/*
 [참고]
  - if( i == 1 && j == 2 ) 처럼 논리 연산자로 합치면 중첩을 줄일 수 있습니다.
*/
