/*
================================================================================
 [문제 019] 논리형 상수 TRUE/FALSE 만들기
================================================================================

 #define으로 TRUE를 1, FALSE를 0으로 정의한 뒤,
 각각을 if 문의 조건으로 사용하여 참인지 거짓인지 출력하세요.

 [실행 결과]
  TRUE의 값은 참입니다.
  FALSE의 값은 거짓입니다.

 [힌트]
  - C 언어(C89)에는 bool 자료형이 없어서 이렇게 상수를 직접 정의해 쓰곤 합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

// ★ 참/거짓을 의미 있는 이름으로 표현하면 코드를 읽기 쉬워집니다.
#define TRUE	1
#define FALSE	0

int main( void )
{
	if( TRUE )		// if( 1 ) → 참
	{
		printf( "TRUE의 값은 참입니다. \n" );
	}
	else
	{
		printf( "TRUE의 값은 거짓입니다. \n" );
	}

	if( FALSE )		// if( 0 ) → 거짓
	{
		printf( "FALSE의 값은 참입니다. \n" );
	}
	else
	{
		printf( "FALSE의 값은 거짓입니다. \n" );
	}

	return 0;
}

/*
 [참고]
  - C99부터는 <stdbool.h>를 포함하면 bool, true, false를 사용할 수 있습니다.
*/
