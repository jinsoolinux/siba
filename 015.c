/*
================================================================================
 [문제 015] 문자열 변수와 문자열 상수
================================================================================

 char 배열 str에 "대한민국"을, char 포인터 j에 "I love Korea"를 저장한 뒤
 %s 서식으로 둘 다 출력하세요.

 [실행 결과]
  문자열형 변수 str의 값은 대한민국
  문자열형 상수 j의 값은 I love Korea

 [힌트]
  - C에는 문자열 자료형이 따로 없고, char 배열이나 char 포인터로 다룹니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

int main( void )
{
	// ★ char 배열: 문자열이 배열에 "복사"되므로 내용을 수정할 수 있습니다.
	//   크기를 생략하면 문자열 길이 + 1(끝의 '\0')만큼 자동으로 잡힙니다.
	char str[] = "대한민국";

	// ★ char 포인터: 문자열 상수가 있는 곳의 "주소"만 가리킵니다.
	//   문자열 상수는 수정하면 안 되므로 const를 붙이는 것이 안전합니다.
	const char *j = "I love Korea";

	printf( "문자열형 변수 str의 값은 %s \n", str );	// ★ 문자열은 %s로 출력
	printf( "문자열형 상수 j의 값은 %s \n", j );

	return 0;
}
