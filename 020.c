/*
================================================================================
 [문제 020] 문자열 상수
================================================================================

 #define으로 KOREA("대한민국")와 BOOK("This is a book.")을 정의하고,
 const char 포인터 SOCCOR에 "나는 축구를 좋아합니다."를 저장한 뒤 세 값을 출력하세요.

 [실행 결과]
  문자열형 상수  KOREA의 값 : 대한민국
  문자열형 상수   BOOK의 값 : This is a book.
  문자열형 상수 SOCCOR의 값 : 나는 축구를 좋아합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

// ★ #define 으로 문자열도 정의할 수 있습니다.
#define KOREA	"대한민국"
#define BOOK	"This is a book."

// ★ const char* : 가리키는 문자열의 내용을 바꿀 수 없는 포인터
const char* SOCCOR = "나는 축구를 좋아합니다.";

int main( void )
{
	printf( "문자열형 상수  KOREA의 값 : %s \n", KOREA );
	printf( "문자열형 상수   BOOK의 값 : %s \n", BOOK );
	printf( "문자열형 상수 SOCCOR의 값 : %s \n", SOCCOR );

	return 0;
}
