/*
================================================================================
 [문제 017] 정수형 상수 (L, UL 접미사)
================================================================================

 아래 코드의 오류를 고쳐서 두 정수형 상수의 값이 출력되도록 하세요.

   #define     HUNDRED_THOUSAND 100000L
   const int   j = 200000UL;
   main()
   {
       HUNDRED_THOUSAND = 100000;
       j = 200000;
       printf( "정수형 상수 HUNDRED_THOUSAND의 값은 %d \n", HUNDRED_THOUSAND );
       printf( "정수형 상수 j의 값은 %d \n", j );
   }

 [고친 후 실행 결과]
  정수형 상수 HUNDRED_THOUSAND의 값은 100000
  정수형 상수 j의 값은 200000

 [힌트]
  - 숫자 뒤의 L은 long, UL은 unsigned long 상수라는 뜻입니다.
  - long 값을 출력할 때는 %ld 서식을 쓰는 것이 정확합니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

#define		HUNDRED_THOUSAND 100000L	// ★ L 접미사 : long 형 상수
const int	j = 200000;					// 원본의 UL은 int 변수에 넣을 때 int로 변환됩니다.

int main( void )
{
	// HUNDRED_THOUSAND = 100000;	// ★ 오류: 상수(숫자)에는 대입할 수 없습니다.
	// j = 200000;					// ★ 오류: const 변수는 값을 바꿀 수 없습니다.

	printf( "정수형 상수 HUNDRED_THOUSAND의 값은 %ld \n", HUNDRED_THOUSAND );	// ★ long → %ld
	printf( "정수형 상수 j의 값은 %d \n", j );

	return 0;
}
