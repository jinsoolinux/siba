/*
================================================================================
 [문제 038] 아스키(ASCII) 코드표 출력하기
================================================================================

 #define으로 ASCII_BEGIN을 0, ASCII_END를 255로 정의하고,
 0부터 255까지의 코드 값과 그에 해당하는 문자를 출력하세요.

 [실행 결과]  (일부만 표시)
  ...
  ASCII 코드 ( 65), 문자 = 'A'
  ASCII 코드 ( 66), 문자 = 'B'
  ASCII 코드 ( 67), 문자 = 'C'
  ...

 [힌트]
  - 같은 정수 값을 %d로 출력하면 숫자, %c로 출력하면 문자가 됩니다.

================================================================================
 아래는 정답 코드입니다. 먼저 직접 풀어 본 뒤 확인하세요.
================================================================================
*/









/* ============================== 정답 코드 ============================== */

#include <stdio.h>

#define	ASCII_BEGIN		0
#define ASCII_END		255

int main( void )
{
	int i;

	for( i = ASCII_BEGIN; i <= ASCII_END; i++ )
	{
		// ★ %3d : 3칸 폭의 정수,  %c : 그 값에 해당하는 문자
		printf( "ASCII 코드 (%3d), 문자 = '%c' \n", i, i );
	}

	return 0;
}

/*
 [참고]
  - 0~31번은 줄바꿈, 탭 같은 제어 문자라서 화면에 이상하게 보일 수 있습니다.
  - 128~255번은 표준 아스키 범위가 아니므로 환경에 따라 다르게 보입니다.
*/
